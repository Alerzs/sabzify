def env_bool(name, default=False):
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in {'1', 'true', 'yes', 'on'}


def env_csv(name, default=''):
    return [item.strip() for item in os.environ.get(name, default).split(',') if item.strip()]



